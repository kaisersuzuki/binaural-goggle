#!/usr/bin/env python3
"""Generate firmware/dspic/src/dds_tables.h (sine, volume law, pot network).

Run from anywhere:  python3 firmware/dspic/tools/gen_tables.py
Re-run only if the constants below change; the output is committed.
"""
import math
import os

SINE_LEN = 1024          # one full cycle, signed Q15

# Volume law: VOL 1..100 % maps to a voltage gain in dB, relative to the
# full-scale PWM sine at the RC filter output. 100 % is deliberately well
# below full scale: the amplifier has far more gain than headphones need.
VOL_TOP_DB = -12.0       # gain at VOL:100
VOL_DB_PER_STEP = 0.48   # so VOL:1 is about -59.5 dB

# Analog network between the filter output and the amplifier input
# (rev 1.1 board): 2 x 10k filter resistors in series, AD5220 50k pot to
# ground, wiper loaded by the TPA6132A2 non-inverting input.
R_SERIES = 20e3
R_POT = 50e3
POT_STEPS = 128
R_WIPER = 40.0
R_AMP_IN = 39.6e3        # IN+ to SGND at 0 dB gain (2 x 19.8k)


def q16(x):
    return max(0, min(65535, int(round(x * 65536))))


def pot_gain(n):
    r_wb = n * R_POT / POT_STEPS + R_WIPER
    r_aw = R_POT - n * R_POT / POT_STEPS
    lower = r_wb * R_AMP_IN / (r_wb + R_AMP_IN)
    return lower / (lower + r_aw + R_SERIES)


def emit(name, ctype, values, per_line):
    out = ["static const %s %s[%d] = {" % (ctype, name, len(values))]
    for i in range(0, len(values), per_line):
        out.append("    " + ",".join("%6d" % v for v in values[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    sine = [int(round(32767 * math.sin(2 * math.pi * i / SINE_LEN)))
            for i in range(SINE_LEN)]
    vol = [0] + [q16(10 ** ((VOL_TOP_DB - VOL_DB_PER_STEP * (100 - p)) / 20))
                 for p in range(1, 101)]
    pot = [q16(pot_gain(n)) for n in range(POT_STEPS)]
    assert all(pot[i] < pot[i + 1] for i in range(POT_STEPS - 1))
    assert vol[100] <= pot[-1], "top volume must be reachable by the pot"

    text = "\n".join([
        "/* dds_tables.h - GENERATED by tools/gen_tables.py, do not edit. */",
        "#ifndef DDS_TABLES_H",
        "#define DDS_TABLES_H",
        "",
        "#include <stdint.h>",
        "",
        "#define SINE_LEN   %d" % SINE_LEN,
        "#define POT_STEPS  %d" % POT_STEPS,
        "",
        "/* One sine cycle, signed Q15. */",
        emit("sine_tab", "int16_t", sine, 12),
        "",
        "/* VOL percent -> voltage gain, Q16 (65536 = full scale). */",
        emit("vol_gain_q16", "uint16_t", vol, 10),
        "",
        "/* AD5220 wiper step -> gain of the pot network, Q16. */",
        emit("pot_gain_q16", "uint16_t", pot, 10),
        "",
        "#endif",
        "",
    ])
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "..", "src", "dds_tables.h")
    with open(path, "w") as f:
        f.write(text)
    print("wrote", os.path.normpath(path))
    print("vol[1]=%d vol[30]=%d vol[100]=%d  pot[1]=%d pot[127]=%d"
          % (vol[1], vol[30], vol[100], pot[1], pot[127]))


if __name__ == "__main__":
    main()
